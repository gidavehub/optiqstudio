// Builds the Horizon '26 brand assets for davelabs.co, amaka.app and optiq.studio.
//
// The masters live in OneDrive at 2752x1536 (Silvery at 5504x3072) and weigh
// 1.5-2MB each. Shipping those directly is what makes the news pages feel slow,
// so every asset is re-encoded once here:
//
//   <name>.webp  2048w  — the source next/image builds its srcset from
//   <name>.jpg   1200w  — Open Graph / Twitter card (crawlers don't do webp)
//   blur.ts             — 16px base64 LQIP so nothing pops in on scroll
//
// Run from the optiq repo (sharp lives here):  node scripts/build-horizon-assets.mjs

import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const SRC = "C:/Users/conne/OneDrive/Desktop/Horizon '26/Official material";

// Every repo gets the same filenames so article content is portable between them.
const TARGETS = [
  "C:/Projects/davelabs/public/horizon",
  "C:/Projects/amakaai/public/horizon",
  "C:/Projects/optiq/public/horizon",
];

const ASSETS = [
  { src: "Horizon Banner.jpg", name: "horizon-banner" },
  { src: "Horizon '26 30th July.jpeg", name: "horizon-july-30" },
  { src: "Amaka AI Hroizon '26.jpeg", name: "amaka-horizon" },
  { src: "Optiq Studio Horizon '26.jpeg", name: "optiq-horizon" },
  { src: "DaveLabs Silvery.jpg", name: "davelabs-silvery" },
  { src: "Dave.jpeg", name: "dave-keynote" },
];

const WEBP_WIDTH = 2048;
const OG_WIDTH = 1200;

async function main() {
  for (const dir of TARGETS) await mkdir(dir, { recursive: true });

  const manifest = {};

  for (const asset of ASSETS) {
    const input = path.join(SRC, asset.src);
    const image = sharp(input);
    const meta = await image.metadata();

    const webp = await sharp(input)
      .resize({ width: Math.min(WEBP_WIDTH, meta.width), withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 })
      .toBuffer();

    const jpg = await sharp(input)
      .resize({ width: Math.min(OG_WIDTH, meta.width), withoutEnlargement: true })
      .jpeg({ quality: 80, mozjpeg: true })
      .toBuffer();

    // LQIP: tiny enough to inline, blurred by next/image's placeholder.
    const lqip = await sharp(input)
      .resize({ width: 16 })
      .webp({ quality: 40 })
      .toBuffer();

    for (const dir of TARGETS) {
      await writeFile(path.join(dir, `${asset.name}.webp`), webp);
      await writeFile(path.join(dir, `${asset.name}.jpg`), jpg);
    }

    const width = Math.min(WEBP_WIDTH, meta.width);
    const height = Math.round((meta.height / meta.width) * width);

    manifest[asset.name] = {
      src: `/horizon/${asset.name}.webp`,
      og: `/horizon/${asset.name}.jpg`,
      width,
      height,
      blurDataURL: `data:image/webp;base64,${lqip.toString("base64")}`,
    };

    const kb = (n) => `${(n / 1024).toFixed(0)}kb`;
    console.log(
      `${asset.name.padEnd(18)} ${meta.width}x${meta.height} -> webp ${kb(webp.length)}  jpg ${kb(jpg.length)}  lqip ${lqip.length}b`
    );
  }

  const ts = `// GENERATED by optiq/scripts/build-horizon-assets.mjs — do not edit by hand.
// Dimensions and LQIP placeholders for the Horizon '26 brand assets in /public/horizon.

export type HorizonAsset = {
  src: string;
  /** 1200w JPEG for Open Graph / Twitter cards — crawlers don't decode webp. */
  og: string;
  width: number;
  height: number;
  blurDataURL: string;
};

export const HORIZON: Record<${Object.keys(manifest)
    .map((k) => JSON.stringify(k))
    .join(" | ")}, HorizonAsset> = ${JSON.stringify(manifest, null, 2)};
`;

  for (const dir of TARGETS) {
    const libDir = path.join(dir, "..", "..", "lib");
    await mkdir(libDir, { recursive: true });
    await writeFile(path.join(libDir, "horizon-assets.ts"), ts);
  }

  console.log(`\nWrote ${ASSETS.length} assets x ${TARGETS.length} repos + lib/horizon-assets.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
